// Copies the DutchAuction ABI from the Foundry build into the frontend.
// Run after `forge build` whenever the contract's functions, events or errors change:
//   cd frontend && npm run sync-abi
import { readFileSync, writeFileSync } from 'node:fs'

const source = new URL('../../contracts/out/DutchAuction.sol/DutchAuction.json', import.meta.url)
const target = new URL('../src/contracts/DutchAuction.abi.ts', import.meta.url)

let abi
try {
  abi = JSON.parse(readFileSync(source, 'utf8')).abi
} catch {
  console.error('Could not read contracts/out/DutchAuction.sol/DutchAuction.json. Run `forge build` in contracts/ first.')
  process.exit(1)
}

writeFileSync(
  target,
  `// Generated by \`npm run sync-abi\` from contracts/out/DutchAuction.sol/DutchAuction.json.\n// Do not edit by hand: change the contract, run \`forge build\`, then \`npm run sync-abi\`.\nexport const dutchAuctionAbi = ${JSON.stringify(abi, null, 2)} as const\n`,
)
console.log(`Wrote ${abi.length} ABI entries to src/contracts/DutchAuction.abi.ts`)
